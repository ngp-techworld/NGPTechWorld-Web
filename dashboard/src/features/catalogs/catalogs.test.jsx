import '@/features/projects/testTimeouts'
import { screen, waitFor, within } from '@testing-library/react'
import { describe, expect, it, vi } from 'vitest'
import { dropOn } from '@/features/projects/dndCapture'
import { mockApi, paginated, reply, validationError } from '@/test/mockApi'
import { renderWithProviders, testUser } from '@/test/renderWithProviders'
import CatalogsPage from './CatalogsPage'
import catalogs from './index'

vi.mock('@dnd-kit/core', async (importOriginal) => (await import('@/features/projects/dndCapture')).withDndCapture(await importOriginal()))

const laravel = { id: 1, name: 'Laravel', slug: 'laravel', category: 'backend' }
const retail = { id: 1, key: 'retail', name_ar: 'التجزئة', name_en: 'Retail', order: 0 }
const health = { id: 2, key: 'health', name_ar: 'الصحة', name_en: 'Health', order: 1 }
const viewer = { ...testUser, is_super_admin: false, role: 'admin', permissions: [], registry_role: 'viewer' }
const dialog = () => within(screen.getByRole('dialog'))

describe('catalogs feature', () => {
  it('is a content entry at /catalogs', () => {
    expect(catalogs).toMatchObject({ id: 'catalogs', nav: { group: 'content', to: '/catalogs' } })
  })
})

describe('technology catalog', () => {
  it('lists, searches and filters the technologies, sorted by name', async () => {
    const api = mockApi({ 'GET /registry/technologies': () => paginated([laravel]) })
    const { user } = renderWithProviders(<CatalogsPage />, { route: '/catalogs' })

    expect(await screen.findByText('Laravel')).toBeInTheDocument()
    expect(api.calls('GET', '/registry/technologies')[0].query).toMatchObject({ sort: 'name', dir: 'asc' })
    await user.selectOptions(screen.getByLabelText('Category'), 'database')
    await user.type(screen.getByRole('searchbox'), 'pos')
    await waitFor(() => expect(api.calls('GET', '/registry/technologies').at(-1).query).toMatchObject({ category: 'database', search: 'pos' }))
  })

  it('adds a technology (a blank slug is generated by the API) and shows a duplicate in words', async () => {
    const api = mockApi({
      'GET /registry/technologies': () => paginated([laravel]),
      'POST /registry/technologies': ({ body }) => (body.name === 'laravel' ? validationError({ name: ['This technology is already in the catalog.'] }) : reply(201, { data: { id: 2, ...body, slug: 'postgresql' } })),
    })
    const { user } = renderWithProviders(<CatalogsPage />, { route: '/catalogs' })
    await screen.findByText('Laravel')

    await user.click(screen.getByRole('button', { name: 'Add technology' }))
    await user.type(dialog().getByLabelText(/^Name/), 'laravel')
    await user.click(dialog().getByRole('button', { name: 'Save' }))
    expect(await dialog().findByText('This technology is already in the catalog.')).toBeInTheDocument()

    await user.clear(dialog().getByLabelText(/^Name/))
    await user.type(dialog().getByLabelText(/^Name/), 'PostgreSQL')
    await user.selectOptions(dialog().getByLabelText('Category'), 'database')
    await user.click(dialog().getByRole('button', { name: 'Save' }))

    await waitFor(() => expect(api.calls('POST', '/registry/technologies')).toHaveLength(2))
    expect(api.calls('POST', '/registry/technologies')[1].body).toEqual({ name: 'PostgreSQL', slug: null, category: 'database' })
  })

  it('explains why a technology still in use cannot be deleted', async () => {
    mockApi({
      'GET /registry/technologies': () => paginated([laravel]),
      'DELETE /registry/technologies/:id': () => validationError({ technology: ['A project still uses this technology.'] }),
    })
    const { user } = renderWithProviders(<CatalogsPage />, { route: '/catalogs' })

    await user.click(await screen.findByRole('button', { name: 'Delete' }))
    await user.click(dialog().getByRole('button', { name: 'Delete' }))
    expect(await screen.findByText('This technology cannot be deleted: at least one project still uses it.')).toBeInTheDocument()
  })

  it('is read-only for a registry viewer', async () => {
    mockApi({ 'GET /registry/technologies': () => paginated([laravel]) })
    renderWithProviders(<CatalogsPage />, { route: '/catalogs', authUser: viewer })

    expect(await screen.findByText('Laravel')).toBeInTheDocument()
    expect(screen.getByText(/Read only: registry managers and project editors/)).toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Add technology' })).not.toBeInTheDocument()
    expect(screen.queryByRole('button', { name: 'Delete' })).not.toBeInTheDocument()
  })

  it('lets a projects-section editor change the catalog', async () => {
    mockApi({ 'GET /registry/technologies': () => paginated([laravel]) })
    renderWithProviders(<CatalogsPage />, { route: '/catalogs', authUser: { ...viewer, registry_role: null, permissions: ['projects'] } })
    expect(await screen.findByRole('button', { name: 'Add technology' })).toBeInTheDocument()
  })
})

describe('industry catalog', () => {
  it('adds an industry with its key and both names', async () => {
    const api = mockApi({
      'GET /registry/industries': () => paginated([retail]),
      'POST /registry/industries': ({ body }) => reply(201, { data: { id: 3, ...body } }),
    })
    const { user } = renderWithProviders(<CatalogsPage />, { route: '/catalogs?tab=industries' })

    expect(await screen.findByText('Retail')).toBeInTheDocument()
    await user.click(screen.getByRole('button', { name: 'Add industry' }))
    await user.type(dialog().getByLabelText(/^Key/), 'Food Delivery')
    await user.click(dialog().getByRole('button', { name: 'Save' }))
    expect(await dialog().findByText('Lowercase letters, numbers and - or _ only, for example online-ordering.')).toBeInTheDocument()

    await user.clear(dialog().getByLabelText(/^Key/))
    await user.type(dialog().getByLabelText(/^Key/), 'food-delivery')
    await user.type(dialog().getByLabelText('Name (Arabic)'), 'توصيل الطعام')
    await user.type(dialog().getByLabelText('Name (English)'), 'Food delivery')
    await user.click(dialog().getByRole('button', { name: 'Save' }))

    await waitFor(() => expect(api.calls('POST', '/registry/industries')).toHaveLength(1))
    expect(api.calls('POST', '/registry/industries')[0].body).toEqual({ key: 'food-delivery', name_ar: 'توصيل الطعام', name_en: 'Food delivery' })
  })

  it('reorders the industries by drag and drop', async () => {
    const api = mockApi({ 'GET /registry/industries': () => paginated([retail, health]), 'POST /registry/industries/reorder': () => null })
    const { user } = renderWithProviders(<CatalogsPage />, { route: '/catalogs?tab=industries' })

    await screen.findByText('Retail')
    await user.click(screen.getByRole('button', { name: 'Reorder' }))
    dropOn(await screen.findByRole('list', { name: 'Industries' }), 1, 2)

    await waitFor(() => expect(api.calls('POST', '/registry/industries/reorder')).toHaveLength(1))
    expect(api.calls('POST', '/registry/industries/reorder')[0].body).toEqual({ ids: [2, 1] })
  })
})
